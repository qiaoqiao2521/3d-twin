import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { access, copyFile, cp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const catalog = JSON.parse(await readFile(join(root, 'integrations/open-demos/catalog.json'), 'utf8'));
const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
export const digest = (bytes) => createHash('sha256').update(bytes).digest('hex');
const gitBlob = (bytes) => createHash('sha1').update(`blob ${bytes.length}\0`).update(bytes).digest('hex');
const exists = async (path) => { try { await access(path); return true; } catch { return false; } };
export function run(command, args, cwd, extra = {}) {
  const result = spawnSync(command, args, { cwd, stdio: 'inherit', env: { ...process.env, NEXT_TELEMETRY_DISABLED: '1', PLAYWRIGHT_SKIP_BROWSER_DOWNLOAD: '1' }, ...extra });
  if (result.error || result.status !== 0) throw new Error(`${command} ${args.join(' ')} failed (${result.status ?? result.error?.message})`);
  return result.stdout;
}
function git(args, cwd) { return run('git', args, cwd, { stdio: 'pipe', encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 }).trim(); }
export function demoById(id) {
  const demo = catalog.find((entry) => entry.id === id);
  if (!demo) throw new Error(`Unknown original demo: ${id}`);
  return demo;
}
export function locations(demo) {
  const cache = join(root, '.cache/open-demos', demo.id);
  return { cache, source: join(cache, 'source'), work: join(cache, 'work'), output: join(root, 'public/open-demos', demo.id) };
}

export async function verifySource(demo) {
  const { source } = locations(demo);
  if (git(['rev-parse', 'HEAD'], source) !== demo.revision || git(['rev-parse', 'HEAD^{tree}'], source) !== demo.tree) {
    throw new Error(`${demo.name}: source revision/tree differs from catalog; no unpinned fallback is allowed.`);
  }
  const records = git(['ls-tree', '-rz', '--long', 'HEAD'], source).split('\0').filter(Boolean).map((line) => {
    const match = line.match(/^(\d+) blob ([a-f0-9]+)\s+(\d+)\t([\s\S]+)$/);
    if (!match) throw new Error(`${demo.name}: unsupported source tree entry ${line}`);
    return { mode: match[1], blob: match[2], bytes: Number(match[3]), path: match[4] };
  });
  for (const file of records) {
    const bytes = await readFile(join(source, file.path));
    if (bytes.length !== file.bytes || gitBlob(bytes) !== file.blob) throw new Error(`${demo.name}: original file changed: ${file.path}`);
  }
  if (records.find((file) => file.path === 'LICENSE')?.blob !== demo.licenseBlob) throw new Error(`${demo.name}: license changed`);
  return records;
}

export async function ensureSource(demo) {
  const { cache, source } = locations(demo);
  await mkdir(cache, { recursive: true });
  if (!(await exists(join(source, '.git')))) {
    await mkdir(source, { recursive: true });
    run('git', ['init', '--quiet'], source);
    run('git', ['remote', 'add', 'origin', demo.repository], source);
  }
  let current = '';
  try { current = git(['rev-parse', 'HEAD'], source); } catch { /* New checkout. */ }
  if (current !== demo.revision) {
    if (current) throw new Error(`${demo.name}: existing cached source uses another revision; move its cache aside before upgrading.`);
    run('git', ['fetch', '--depth=1', 'origin', demo.revision], source);
    run('git', ['checkout', '--detach', demo.revision], source);
  }
  return verifySource(demo);
}

async function fingerprint(demo) {
  const inputs = ['scripts/open-demos.mjs', 'integrations/open-demos/catalog.json', 'integrations/open-demos/lifecycle.js', 'integrations/open-demos/rftwin-start.ts.txt'];
  return digest(Buffer.concat([Buffer.from(demo.revision), ...await Promise.all(inputs.map((path) => readFile(join(root, path))))]));
}
async function replaceChecked(file, from, to) {
  const original = await readFile(file, 'utf8');
  if (!original.includes(from)) throw new Error(`Original adapter anchor no longer exists: ${file}: ${from}`);
  await writeFile(file, original.replace(from, to));
}

export function adaptRftwinReplayBanner(code) {
  const messages = [
    [
      'Local Demo — deterministic replay generated by the Python twin engine (seed 42 · 5 min loop). Live-only functions are disabled; reconnecting in the background.',
      'Local Demo — deterministic replay generated by the Python twin engine (seed 42 · 5 min loop). Live-only functions are disabled. This local replay does not connect to the live backend.',
    ],
    [
      'Local Demo — 由 Python 引擎預先產生的確定性回放（seed 42 · 5 分鐘循環）。需要 Live 的功能已停用；背景持續嘗試重新連線。',
      'Local Demo — 由 Python 引擎預先產生的確定性回放（seed 42 · 5 分鐘循環）。需要 Live 的功能已停用；此本地回放不會連接即時後端。',
    ],
  ];
  for (const [original, local] of messages) {
    const from = `"conn.demo": ${JSON.stringify(original)},`;
    if (!code.includes(from)) throw new Error('RFTwin original replay banner changed');
    code = code.replace(from, `"conn.demo": new URLSearchParams(location.search).get('source') === 'local' ? ${JSON.stringify(local)} : ${JSON.stringify(original)},`);
  }
  return code;
}

async function localWareFonts(frontend) {
  const dir = join(frontend, 'public/fonts');
  await mkdir(dir, { recursive: true });
  const rules = [];
  for (const [family, key, weights] of [['Inter', 'inter', [400, 500, 600, 700]], ['JetBrains Mono', 'jetbrains-mono', [500]]]) {
    const pkg = join(root, 'node_modules/@fontsource', key);
    for (const weight of weights) {
      const name = `${key}-latin-${weight}-normal.woff2`;
      await copyFile(join(pkg, 'files', name), join(dir, name));
      rules.push(`@font-face{font-family:'${family}';font-style:normal;font-weight:${weight};font-display:swap;src:url('./${name}') format('woff2')}`);
    }
    await copyFile(join(pkg, 'LICENSE'), join(dir, `${key}-OFL.txt`));
    await copyFile(join(pkg, 'package.json'), join(dir, `${key}-package.json`));
  }
  await writeFile(join(dir, 'fonts.css'), rules.join('\n'));
  const index = join(frontend, 'index.html');
  const html = await readFile(index, 'utf8');
  if (!html.includes('https://fonts.googleapis.com/css2?family=Inter')) throw new Error('WareTwin font source changed');
  await writeFile(index, html.replace(/\s*<link[^>]+https:\/\/fonts\.googleapis\.com[^>]+>/g, '')
    .replace('</head>', '<link href="/fonts/fonts.css" rel="stylesheet" /></head>'));
}

export async function prepareDemo(demo) {
  const records = await ensureSource(demo);
  const paths = locations(demo);
  const stamp = await fingerprint(demo);
  const prepared = join(paths.work, '.host-prepared');
  if (!(await exists(prepared)) || (await readFile(prepared, 'utf8')) !== stamp) {
    await rm(paths.work, { recursive: true, force: true });
    await mkdir(paths.work, { recursive: true });
    for (const file of records) {
      const dest = join(paths.work, file.path);
      await mkdir(dirname(dest), { recursive: true });
      await copyFile(join(paths.source, file.path), dest);
    }
    const frontend = resolve(paths.work, demo.frontend);
    if (demo.id === 'warehouse-journey') {
      await writeFile(join(frontend, 'next.config.ts'), `import type { NextConfig } from 'next';\nconst config: NextConfig = { reactStrictMode: true, output: 'export', basePath: '/open-demos/warehouse-journey', assetPrefix: '/open-demos/warehouse-journey', trailingSlash: true, outputFileTracingRoot: process.cwd(), experimental: { cpus: 2 } };\nexport default config;\n`);
      // Isolate the original app from the host's Tailwind/PostCSS config.
      await writeFile(join(frontend, 'postcss.config.json'), JSON.stringify({ plugins: [
        'next/dist/compiled/postcss-flexbugs-fixes',
        ['next/dist/compiled/postcss-preset-env', { autoprefixer: { flexbox: 'no-2009' }, stage: 3, features: { 'custom-properties': false } }],
      ] }));
      await replaceChecked(join(frontend, 'src/app/layout.tsx'), 'url: "/screenshots/warehouse-interior.jpg"', 'url: "/open-demos/warehouse-journey/screenshots/warehouse-interior.jpg"');
      for (const path of ['src/components/SceneText.tsx', 'src/app/globals.css']) {
        const target = join(frontend, path);
        const code = await readFile(target, 'utf8');
        if (!code.includes('"/fonts/')) throw new Error(`Journey font path changed: ${path}`);
        await writeFile(target, code.replaceAll('"/fonts/', '"/open-demos/warehouse-journey/fonts/'));
      }
    } else {
      await writeFile(join(frontend, 'src/host.d.ts'), 'interface Window { __openDemoHost?: { register(cleanup: () => void): void; report(status: string): void } }\n');
      const main = join(frontend, 'src/main.tsx');
      const create = demo.id === 'waretwin' ? 'ReactDOM.createRoot' : 'createRoot';
      await replaceChecked(main, `${create}(document.getElementById("root")!).render(`, `const root = ${create}(document.getElementById("root")!);\nroot.render(`);
      const store = demo.id === 'waretwin' ? 'useStore' : 'useTwin';
      const field = demo.id === 'waretwin' ? 'source' : 'mode';
      await writeFile(main, (await readFile(main, 'utf8')) + `\nimport { ${store} } from './state/store';\nconst host = window.__openDemoHost;\nconst unsubscribe = ${store}.subscribe((state) => host?.report(state.${field}));\nhost?.report(${store}.getState().${field});\nhost?.register(() => { unsubscribe(); root.unmount(); });\n`);
      if (demo.id === 'waretwin') {
        const transport = join(frontend, 'src/services/ws.ts');
        await replaceChecked(transport, 'const WS_URL = (import.meta as unknown as { env: Record<string, string | undefined> }).env?.VITE_WS_URL ?? `ws://${location.hostname}:8000/ws`;',
          `const endpoint = new URL('/open-demo-api/waretwin/ws', location.href);\nendpoint.protocol = location.protocol === 'https:' ? 'wss:' : 'ws:';\nconst WS_URL = endpoint.href;`);
        await replaceChecked(transport, '  stopped = false; onStateChange = onChange;\n  open();',
          `  stopped = false; onStateChange = onChange;\n  if (new URLSearchParams(location.search).get('source') === 'local') { onChange('offline'); return; }\n  open();`);
        await localWareFonts(frontend);
      } else {
        await copyFile(join(root, 'integrations/open-demos/rftwin-start.ts.txt'), join(frontend, 'src/host-start.ts'));
        await replaceChecked(join(frontend, 'src/App.tsx'), 'import { start, useTwin } from "./state/store";', 'import { useTwin } from "./state/store";\nimport { start } from "./host-start";');
        const translations = join(frontend, 'src/i18n/index.ts');
        await writeFile(translations, adaptRftwinReplayBanner(await readFile(translations, 'utf8')));
        await writeFile(join(frontend, 'src/config.ts'), `/** Host deployment URLs only. The original API/WS protocol is unchanged. */\nexport const API_BASE = '/open-demo-api/rftwin';\nexport function apiUrl(path: string): string { return path.startsWith('/api/') ? API_BASE + path : path; }\nexport function wsUrl(): string { const url = new URL(API_BASE + '/ws', location.href); url.protocol = location.protocol === 'https:' ? 'wss:' : 'ws:'; return url.href; }\n`);
        for (const path of ['src/panels/Panels.tsx', 'src/panels/Views.tsx']) {
          const file = join(frontend, path);
          const code = await readFile(file, 'utf8');
          await writeFile(file, code.replace(/src=\{(latest|f)\.image_url \?\? apiUrl\((`[^`]+`)\)\}/g, 'src={apiUrl($1.image_url ?? $2)}'));
        }
      }
    }
    await writeFile(prepared, stamp);
  }
  const frontend = resolve(paths.work, demo.frontend);
  const lock = digest(await readFile(join(frontend, 'package-lock.json')));
  const installed = join(frontend, 'node_modules/.host-install');
  if (!(await exists(installed)) || (await readFile(installed, 'utf8')) !== lock) {
    // Vite can set NODE_ENV in this process; all original builds need dev tools.
    run(npm, ['ci', '--include=dev', '--no-audit', '--no-fund'], frontend);
    await writeFile(installed, lock);
  }
  return { ...paths, frontend, records, stamp };
}

export async function listFiles(directory, prefix = '') {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) files.push(...await listFiles(join(directory, entry.name), path));
    else if (entry.isFile()) files.push(path);
  }
  return files.sort();
}

async function buildDemo(demo) {
  const { frontend, source, output, records, stamp } = await prepareDemo(demo);
  if (demo.id === 'warehouse-journey') {
    run(npm, ['run', 'build'], frontend);
    await rm(output, { recursive: true, force: true });
    await cp(join(frontend, 'out'), output, { recursive: true });
  } else {
    run(process.execPath, [join(frontend, 'node_modules/typescript/bin/tsc'), '--noEmit'], frontend);
    const { build } = await import(pathToFileURL(join(frontend, 'node_modules/vite/dist/node/index.js')).href);
    await build({ root: frontend, configFile: join(frontend, 'vite.config.ts'), base: './', css: { postcss: { plugins: [] } }, build: { outDir: output, emptyOutDir: true } });
  }
  const htmlFile = join(output, 'index.html');
  await writeFile(htmlFile, (await readFile(htmlFile, 'utf8')).replace('<head>', `<head><meta name="open-demo-id" content="${demo.id}"><script src="./host-lifecycle.js"></script>`));
  await copyFile(join(root, 'integrations/open-demos/lifecycle.js'), join(output, 'host-lifecycle.js'));
  await copyFile(join(source, 'LICENSE'), join(output, 'LICENSE.txt'));
  await copyFile(join(source, 'README.md'), join(output, 'UPSTREAM-README.md'));
  await writeFile(join(output, 'SOURCE.json'), JSON.stringify({ ...demo, adapterFingerprint: stamp, sourceFiles: records }, null, 2) + '\n');
  const resources = [];
  for (const path of await listFiles(output)) {
    if (path === 'ASSET-MANIFEST.json') continue;
    const bytes = await readFile(join(output, path));
    resources.push({ path, bytes: bytes.length, sha256: digest(bytes) });
  }
  await writeFile(join(output, 'ASSET-MANIFEST.json'), JSON.stringify({ id: demo.id, revision: demo.revision, resources }, null, 2) + '\n');
  await verifySource(demo);
  console.log(`${demo.name}: ${records.length} unchanged original files; ${resources.length} built resources → public/open-demos/${demo.id}/`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const action = process.argv[2] || 'build';
    const selected = process.argv[3] ? [demoById(process.argv[3])] : catalog;
    if (!['install', 'build', 'verify-sources'].includes(action)) throw new Error('Usage: node scripts/open-demos.mjs install|build|verify-sources [id]');
    for (const demo of selected) {
      if (action === 'build') await buildDemo(demo);
      else if (action === 'install') await prepareDemo(demo);
      else { const files = await verifySource(demo); console.log(`${demo.name}: ${files.length} original blobs verified`); }
    }
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
